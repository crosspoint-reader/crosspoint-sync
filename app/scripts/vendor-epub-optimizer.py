#!/usr/bin/env python3
"""Extract the pinned reader optimizer. Usage: python3 scripts/vendor-epub-optimizer.py READER_REPO"""

from pathlib import Path
import subprocess
import sys

REVISION = "facaa87e379a499855e5980edd47beba4d01c884"
SOURCE = "src/network/html/FilesPage.html"
DEST = Path(__file__).resolve().parents[1] / "src/epub/vendor"


def read(path):
    return subprocess.check_output(["git", "-C", sys.argv[1], "show", f"{REVISION}:{path}"], text=True)


def between(text, start, end):
    return text[text.index(start):text.index(end)]


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"Expected one match: {old[:100]}")
    return text.replace(old, new, 1)


source = read(SOURCE)
license_text = read("LICENSE")
core = between(source, "const DEFENSIVE_STYLE", "function sanitizeMetadataFilenamePart")
core += between(source, "function resolvePath", "// Get WebSocket URL")
crop_constants = between(source, "const CROP_WHITE_THRESHOLD", "// Note: Overlap")

# Replace DOM logging with the host's callback; keep the original log call sites.
import re
core = re.sub(r"(?m)^[ \t]*(?:clearLog|showLog)\([^\n]*\);\n", "", core)
core = replace_once(core, "${file.name}</strong>", "${escapeHtml(file.name)}</strong>")
export_log = between(core, "  // Auto-export only if NOT in batch mode", "  return newBlob;")
core = replace_once(core, export_log, "")

# Upstream's fallback writes undecodable PNG bytes under a .jpg name. Stop instead.
fallback = between(core, "        // Log error but continue with original image", "      const parts = result.parts;")
core = replace_once(core, fallback, """        throw new Error(`Could not optimize image ${path}: ${imageError.message}`);
      }

""")

# Reject books upstream cannot preserve, before doing any expensive image work.
core = replace_once(core, "  const entries = Object.entries(zip.files);", """  const entries = Object.entries(zip.files);
  const opfPaths = entries.filter(([path, entry]) => !entry.dir && path.toLowerCase().endsWith('.opf'));
  if (opfPaths.length !== 1) {
    throw new Error('Optimization requires an EPUB with one package document. Turn off Optimize EPUB to send the original.');
  }
  const outputImages = new Set();
  for (const [path, entry] of entries) {
    if (entry.dir || !/\\.(png|gif|webp|bmp|jpg|jpeg)$/i.test(path)) continue;
    const outputPath = path.replace(/\\.[^.]+$/, '.jpg');
    if (outputImages.has(outputPath)) throw new Error(`Images would overwrite each other: ${outputPath}`);
    outputImages.add(outputPath);
  }""")

# Exceptions in an async DOM callback otherwise leave processImage pending forever.
core = replace_once(core, "    img.onload = async () => {\n", "    img.onload = async () => {\n      try {\n")
core = replace_once(core, "    };\n    img.onerror = () => {", """      } catch (error) {
        reject(error);
      }
    };
    img.onerror = () => {""")

header = f"""/*!
{license_text.rstrip()}
*/
// Generated by scripts/vendor-epub-optimizer.py; do not edit directly.
// https://github.com/crosspoint-reader/crosspoint-reader/blob/{REVISION}/{SOURCE}
// See README.md for host adaptations and the supported settings.

import JSZip from 'jszip'
import {{ createConversionLogger }} from '../log.js'

// Every invocation owns its settings and cancellation state.
export async function convertEpub(file, options, onProgress, signal, onLog) {{
  const {{ log, logImage, logFix, logSummary, formatBytes, escapeHtml, error: logError }} = createConversionLogger(onLog);
  const {{ width: MAX_WIDTH, height: MAX_HEIGHT, quality: JPEG_QUALITY }} = options;
  const ENABLE_GRAYSCALE = true;
  const ENABLE_AUTO_CROP = false;
  const HANDEDNESS = 'right';
  const OVERLAP_PERCENT = 5;
  const autoCropProtectedPaths = new Set();
  const getImageState = () => 0;
  let operationCancelled = !!signal?.aborted;
  const cancel = () => {{ operationCancelled = true; }};

"""

footer = """
  signal?.addEventListener('abort', cancel, { once: true });
  try {
    signal?.throwIfAborted();
    const result = await convertEpubFile(file, onProgress);
    signal?.throwIfAborted();
    return result;
  } catch (error) {
    logError(error.message || String(error));
    throw error;
  } finally {
    signal?.removeEventListener('abort', cancel);
  }
}
"""

DEST.mkdir(parents=True, exist_ok=True)
(DEST / "optimizer.js").write_text(header + crop_constants + "\n" + core + footer)
(DEST / "LICENSE").write_text(license_text)
print(f"Vendored {REVISION} → {DEST / 'optimizer.js'}")
